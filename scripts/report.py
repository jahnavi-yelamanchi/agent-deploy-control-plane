"""runs/*.jsonl -> results/results.md (one table) + results/cost_vs_quality.png.

    python scripts/report.py [--runs runs] [--out results]

Rows are deduplicated on (experiment, variant), last write wins. Output is deterministic for a
given set of rows (no timestamps in the markdown, fixed PNG metadata).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

EXPERIMENT_ORDER = (
    "offline",
    "gate",
    "models",
    "caching",
    "context",
    "canary_weight",
    "rollback_rule",
    "demo",
    "chaos",
)
# Categorical slots (fixed order) + marker per experiment as secondary encoding.
PALETTE = ("#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948")
MARKERS = ("o", "s", "D", "^", "v", "P", "X", "h")
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"

COLUMNS = (
    ("experiment", "experiment", "{}"),
    ("variant", "variant", "{}"),
    ("model_id", "model", "{}"),
    ("task_success", "success", "{:.2f}"),
    ("eval_score", "eval score", "{:.3f}"),
    ("cost_per_task", "cost/task", "${:.5f}"),
    ("p50_latency_ms", "p50 ms", "{:.0f}"),
    ("p95_latency_ms", "p95 ms", "{:.0f}"),
    ("cache_hit_rate", "cache hit", "{:.2f}"),
    ("rollback_triggered", "rollback", "{}"),
    ("time_to_detect_s", "TTD s", "{:.1f}"),
    ("false_rollbacks", "false rollbacks", "{}"),
)


def load_rows(runs_dir: Path) -> list[dict[str, Any]]:
    rows: dict[tuple[str, str], dict[str, Any]] = {}
    for path in sorted(runs_dir.glob("*.jsonl")):
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            key = (str(row.get("experiment") or path.stem), str(row.get("variant") or ""))
            row["experiment"], row["variant"] = key
            rows.pop(key, None)
            rows[key] = row

    def order(item: tuple[int, dict[str, Any]]) -> tuple[int, str, int]:
        i, r = item
        exp = r["experiment"]
        rank = EXPERIMENT_ORDER.index(exp) if exp in EXPERIMENT_ORDER else len(EXPERIMENT_ORDER)
        return rank, exp, i

    return [r for _, r in sorted(enumerate(rows.values()), key=order)]


def fmt(value: Any, spec: str) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    try:
        return spec.format(value)
    except (ValueError, TypeError):
        return str(value)


def render_markdown(rows: list[dict[str, Any]]) -> str:
    head = "| " + " | ".join(c[1] for c in COLUMNS) + " |"
    sep = "|" + "|".join("---" if i < 3 else "---:" for i in range(len(COLUMNS))) + "|"
    body = ["| " + " | ".join(fmt(r.get(k), f) for k, _, f in COLUMNS) + " |" for r in rows]
    return (
        "# Results\n\n"
        "Generated by `scripts/report.py` from `runs/*.jsonl`. MODEL_PROVIDER=mock unless noted; "
        "frozen set evals/frozen/v1 (50 tasks).\n\n" + "\n".join([head, sep, *body]) + "\n"
    )


def pareto_front(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Non-dominated points (min cost, max score), sorted by cost."""
    front: list[tuple[float, float]] = []
    for cost, score in sorted(points, key=lambda p: (p[0], -p[1])):
        if not front or score > front[-1][1]:
            front.append((cost, score))
    return front


def render_plot(rows: list[dict[str, Any]], path: Path) -> int:
    pts = [
        r for r in rows if r.get("cost_per_task") is not None and r.get("eval_score") is not None
    ]
    fig, ax = plt.subplots(figsize=(12, 7.5), dpi=100)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    experiments = list(dict.fromkeys(r["experiment"] for r in pts))
    for i, exp in enumerate(experiments):
        sub = [r for r in pts if r["experiment"] == exp]
        ax.scatter(
            [r["cost_per_task"] for r in sub],
            [r["eval_score"] for r in sub],
            s=80,
            marker=MARKERS[i % len(MARKERS)],
            color=PALETTE[i % len(PALETTE)],
            edgecolor=SURFACE,
            linewidth=2,
            label=exp,
            zorder=3,
        )
    # one label per coincident point (e.g. v1 == sonnet == cache-on)
    groups: dict[tuple[float, float], list[str]] = {}
    for r in pts:
        c, q = r["cost_per_task"], r["eval_score"]
        key = next(
            (k for k in groups if abs(k[1] - q) < 0.004 and abs(c - k[0]) <= 0.05 * max(c, k[0])),
            (c, q),
        )
        groups.setdefault(key, []).append(r["variant"])
    for (cost, score), names in groups.items():
        names = list(dict.fromkeys(names))
        text = "\n".join(", ".join(names[i : i + 3]) for i in range(0, len(names), 3))
        ax.annotate(
            text,
            (cost, score),
            xytext=(8, -4),
            textcoords="offset points",
            fontsize=9,
            color=MUTED,
            va="top",
        )
    front = pareto_front([(r["cost_per_task"], r["eval_score"]) for r in pts])
    if len(front) > 1:
        ax.plot(*zip(*front, strict=True), color=INK, lw=1.5, ls="--", zorder=2, label="Pareto")
    costs = [r["cost_per_task"] for r in pts if r["cost_per_task"] > 0]
    if costs and max(costs) / min(costs) > 20:
        ax.set_xscale("log")
    ax.set_xlabel("cost per task (USD)", color=INK)
    ax.set_ylabel("eval score (0-1)", color=INK)
    ax.set_title("Cost vs quality, frozen eval set (mock provider)", color=INK, loc="left")
    ax.grid(True, color=GRID, lw=0.8)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
    ax.tick_params(colors=MUTED)
    if pts:
        ax.legend(frameon=False, loc="upper left", fontsize=9)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, facecolor=SURFACE, metadata={"Software": None})
    plt.close(fig)
    return len(pts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="render results table + cost/quality plot")
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default="results")
    args = ap.parse_args(argv)
    rows = load_rows(Path(args.runs))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.md").write_text(render_markdown(rows))
    n = render_plot(rows, out / "cost_vs_quality.png")
    print(f"{len(rows)} rows -> {out / 'results.md'}; {n} points -> {out / 'cost_vs_quality.png'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
