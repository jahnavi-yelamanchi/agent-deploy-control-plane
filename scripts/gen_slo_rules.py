"""Render slo/slo.yaml (Sloth prometheus/v1) into Prometheus rules without Sloth.

Per SLO:
  slo:sli_error:ratio_rate<w>   w in 5m,30m,1h,2h,6h,1d,3d,30d (30d = mean of 5m ratios)
  slo:burn_rate:<w>             error ratio / (1 - objective)
  slo:error_budget:remaining    1 - 30d error ratio / budget
  slo:objective:ratio, slo:error_budget:ratio, slo:time_period:days
  <alerting.name>Page           14.4x over 1h & 5m, or 6x over 6h & 30m
  <alerting.name>Ticket         3x over 1d & 2h, or 1x over 3d & 6h
Multiwindow multi-burn-rate thresholds per the Google SRE workbook, ch. 5.

Usage: gen_slo_rules.py [--spec slo/slo.yaml] [--out <rules.yml>] [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SPEC = ROOT / "slo" / "slo.yaml"
DEFAULT_OUT = ROOT / "observability" / "prometheus" / "rules" / "slo-generated.yml"

WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
PERIOD = "30d"
PERIOD_DAYS = 30

# (severity, [(long, short, factor), ...])
ALERTS: list[tuple[str, list[tuple[str, str, float]]]] = [
    ("page", [("1h", "5m", 14.4), ("6h", "30m", 6.0)]),
    ("ticket", [("1d", "2h", 3.0), ("3d", "6h", 1.0)]),
]

HEADER = "# GENERATED by scripts/gen_slo_rules.py from slo/slo.yaml. Do not edit.\n"


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def _fmt(x: float) -> str:
    return f"{x:.10g}"


def _squash(q: str) -> str:
    return " ".join(q.split())


def _sli_expr(sli: dict[str, Any], window: str) -> str:
    if "raw" in sli:
        q = sli["raw"]["error_ratio_query"]
        return _squash(q.replace("{{.window}}", window))
    ev = sli["events"]
    err = _squash(ev["error_query"].replace("{{.window}}", window))
    tot = _squash(ev["total_query"].replace("{{.window}}", window))
    return f"({err})\n/\n({tot})"


def _slo_rules(service: str, base_labels: dict[str, str], slo: dict[str, Any]) -> list[dict]:
    name = slo["name"]
    sid = f"{service}-{name}"
    objective = float(slo["objective"]) / 100.0
    budget = 1.0 - objective
    sel = f'{{sloth_id="{sid}", sloth_service="{service}", sloth_slo="{name}"}}'
    ids = {"sloth_id": sid, "sloth_service": service, "sloth_slo": name}
    labels = {**base_labels, **slo.get("labels", {}), **ids}

    sli_rules: list[dict] = []
    for w in WINDOWS:
        sli_rules.append(
            {
                "record": f"slo:sli_error:ratio_rate{w}",
                "expr": _sli_expr(slo["sli"], w),
                "labels": {**labels, "sloth_window": w},
            }
        )
    sli_rules.append(
        {
            "record": f"slo:sli_error:ratio_rate{PERIOD}",
            "expr": (
                f"sum_over_time(slo:sli_error:ratio_rate5m{sel}[{PERIOD}])\n"
                f"/ ignoring (sloth_window)\n"
                f"count_over_time(slo:sli_error:ratio_rate5m{sel}[{PERIOD}])"
            ),
            "labels": {**labels, "sloth_window": PERIOD},
        }
    )

    meta_rules: list[dict] = [
        {"record": "slo:objective:ratio", "expr": f"vector({_fmt(objective)})", "labels": labels},
        {"record": "slo:error_budget:ratio", "expr": f"vector({_fmt(budget)})", "labels": labels},
        {"record": "slo:time_period:days", "expr": f"vector({PERIOD_DAYS})", "labels": labels},
    ]
    for w in [*WINDOWS, PERIOD]:
        meta_rules.append(
            {
                "record": f"slo:burn_rate:{w}",
                "expr": f"slo:sli_error:ratio_rate{w}{sel} / {_fmt(budget)}",
                "labels": {**labels, "sloth_window": w},
            }
        )
    meta_rules.append(
        {
            "record": "slo:error_budget:remaining",
            "expr": f"1 - slo:sli_error:ratio_rate{PERIOD}{sel} / {_fmt(budget)}",
            "labels": labels,
        }
    )

    alert_rules: list[dict] = []
    alerting = slo.get("alerting") or {}
    if alerting.get("name"):
        for severity, pairs in ALERTS:
            cfg = alerting.get(f"{severity}_alert") or {}
            if cfg.get("disable"):
                continue
            clauses = [
                f"(\n  slo:burn_rate:{long_w}{sel} > {_fmt(f)}\n"
                f"  and ignoring (sloth_window)\n"
                f"  slo:burn_rate:{short_w}{sel} > {_fmt(f)}\n)"
                for long_w, short_w, f in pairs
            ]
            windows_desc = ", ".join(f"{f:g}x over {lw}&{sw}" for lw, sw, f in pairs)
            alert_rules.append(
                {
                    "alert": f"{alerting['name']}{severity.capitalize()}",
                    "expr": "max without (sloth_window) (\n"
                    + "\nor ignoring (sloth_window)\n".join(clauses)
                    + "\n)",
                    "labels": {
                        **alerting.get("labels", {}),
                        **cfg.get("labels", {}),
                        "sloth_severity": severity,
                        **ids,
                    },
                    "annotations": {
                        **alerting.get("annotations", {}),
                        **cfg.get("annotations", {}),
                        "description": (
                            f"{service}/{name} SLO {slo['objective']}% burning error budget "
                            f"({windows_desc})."
                        ),
                    },
                }
            )

    groups = [
        {"name": f"slo-sli-recordings-{sid}", "rules": sli_rules},
        {"name": f"slo-meta-recordings-{sid}", "rules": meta_rules},
    ]
    if alert_rules:
        groups.append({"name": f"slo-alerts-{sid}", "rules": alert_rules})
    return groups


def render(spec_path: Path = DEFAULT_SPEC) -> str:
    spec = yaml.safe_load(spec_path.read_text())
    if spec.get("version") != "prometheus/v1":
        raise ValueError(f"unsupported spec version: {spec.get('version')!r}")
    service = spec["service"]
    base_labels = dict(spec.get("labels") or {})
    groups: list[dict] = []
    for slo in spec["slos"]:
        groups.extend(_slo_rules(service, base_labels, slo))
    body = yaml.dump(
        {"groups": groups}, Dumper=_Dumper, sort_keys=False, width=100, default_flow_style=False
    )
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is stale")
    args = ap.parse_args(argv)

    text = render(args.spec)
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"stale: {args.out} (run scripts/gen_slo_rules.py)", file=sys.stderr)
            return 1
        print(f"ok: {args.out}")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
